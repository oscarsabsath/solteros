-- 1. TABLA DE PERFILES DE USUARIOS
create table if not exists public.profiles (
  id uuid references auth.users on delete cascade primary key,
  full_name text not null,
  age integer check (age >= 18),
  gender text check (gender in ('Hombre', 'Mujer', 'Otro')),
  country text default '',
  city text default '',
  church_name text default '', -- Nombre o distrito de la Iglesia Adventista
  bio text default '',
  avatar_url text default '',
  interests text[] default '{}',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. ACTIVAR ROW LEVEL SECURITY (RLS)
alter table public.profiles enable row level security;

-- 3. POLÍTICAS DE SEGURIDAD PARA PERFILES
create policy "Cualquier usuario autenticado puede ver perfiles"
  on public.profiles for select
  using (auth.role() = 'authenticated');

create policy "Los usuarios pueden insertar su propio perfil"
  on public.profiles for insert
  with check (auth.uid() = id);

create policy "Los usuarios pueden actualizar su propio perfil"
  on public.profiles for update
  using (auth.uid() = id);

-- 4. TABLA DE CONEXIONES Y LIKES
create table if not exists public.likes (
  id bigint generated by default as identity primary key,
  from_user uuid references public.profiles(id) on delete cascade not null,
  to_user uuid references public.profiles(id) on delete cascade not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  unique(from_user, to_user)
);

alter table public.likes enable row level security;

create policy "Usuarios pueden ver sus likes recibidos y dados"
  on public.likes for select
  using (auth.uid() = from_user or auth.uid() = to_user);

create policy "Usuarios pueden enviar likes"
  on public.likes for insert
  with check (auth.uid() = from_user);

-- 5. TRIGGER AUTOMÁTICO AL CREAR USUARIO EN AUTH (OPCIONAL)
-- Sincroniza metadatos del usuario creado a la tabla de perfiles
create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, full_name, age, gender, country, city, church_name, bio)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', 'Usuario'),
    coalesce((new.raw_user_meta_data->>'age')::integer, 25),
    coalesce(new.raw_user_meta_data->>'gender', 'Hombre'),
    coalesce(new.raw_user_meta_data->>'country', ''),
    coalesce(new.raw_user_meta_data->>'city', ''),
    coalesce(new.raw_user_meta_data->>'church_name', ''),
    coalesce(new.raw_user_meta_data->>'bio', '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$ language plpgsql security definer;

-- Trigger disparador
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();
